def _mask(value: str) -> str:
    """Mask a secret value, showing only the last 4 characters."""
    if not value:
        return ""
    if len(value) <= 4:
        return "*" * len(value)
    return "*" * (len(value) - 4) + value[-4:]


def _load_config() -> dict[str, Any]:
    if not MCP_CONFIG_PATH.exists():
        return {"mcpServers": {}}
    try:
        data = json.loads(MCP_CONFIG_PATH.read_text(encoding="utf-8"))
    except Exception:
        return {"mcpServers": {}}
    data.setdefault("mcpServers", {})
    return data


def _extract_value(server: dict[str, Any], field_name: str) -> str:
    """Pull a stored field value back out of an mcpServers entry, given the
    field's cfg-key name (e.g. "elevenlabs_key", "postiz_url")."""
    env = server.get("env", {}) or {}
    headers = server.get("headers", {}) or {}
    auth = headers.get("Authorization", "") if isinstance(headers, dict) else ""
    bearer = auth[len("Bearer "):] if auth.startswith("Bearer ") else ""

    if field_name == "elevenlabs_key":
        return env.get("ELEVENLABS_API_KEY", "")
    if field_name == "revenuecat_key":
        return bearer
    if field_name == "postiz_url":
        url = server.get("url", "")
        if "/mcp/" in url:
            return url.split("/mcp/")[0]
        return url
    if field_name == "postiz_key":
        url = server.get("url", "")
        if "/mcp/" in url:
            return url.split("/mcp/", 1)[1]
        return ""
    if field_name == "homeassistant_url":
        url = server.get("url", "")
        suffix = "/mcp_server/sse"
        if url.endswith(suffix):
            return url[: -len(suffix)]
        return url
    if field_name == "homeassistant_token":
        return bearer
    if field_name == "exa_key":
        url = server.get("url", "")
        if "exaApiKey=" in url:
            return url.split("exaApiKey=", 1)[1]
        return ""
    if field_name == "github_token":
        return env.get("GITHUB_PERSONAL_ACCESS_TOKEN", "")
    if field_name == "notion_token":
        return env.get("NOTION_TOKEN", "")
    if field_name == "mem0_key":
        return env.get("MEM0_API_KEY", "")
    if field_name == "stripe_key":
        return bearer
    if field_name == "slack_token":
        return env.get("SLACK_BOT_TOKEN", "")
    if field_name == "obsidian_vault_path":
        args = server.get("args", [])
        # mcp-obsidian: npx -y mcp-obsidian <vault_path>
        if args and len(args) >= 3 and args[1] == "mcp-obsidian":
            return args[-1]
        return ""
    if field_name == "spotify_client_id":
        return env.get("SPOTIFY_CLIENT_ID", "")
    if field_name == "spotify_client_secret":
        return env.get("SPOTIFY_CLIENT_SECRET", "")
    if field_name == "weather_api_key":
        return env.get("OPENWEATHERMAP_API_KEY", "")
    return ""


def get_connectors_status() -> dict[str, Any]:
    """Return status + masked field values for every connector."""
    data = _load_config()
    servers: dict[str, Any] = data.get("mcpServers", {})

    result = []
    for c in CONNECTORS:
        server = servers.get(c["id"])
        enabled = server is not None
        values: dict[str, str] = {}
        for f in c["fields"]:
            raw = _extract_value(server, f["name"]) if enabled else ""
            if f["type"] == "password":
                values[f["name"]] = _mask(raw)
            else:
                values[f["name"]] = raw
        result.append(
            {
                "id": c["id"],
                "label": c["label"],
                "description": c["description"],
                "category": c.get("category", ""),
                "available_soon": c.get("available_soon", False),
                "fields": c["fields"],
                "enabled": enabled,
                "values": values,
            }
        )
    return {"ok": True, "connectors": result}



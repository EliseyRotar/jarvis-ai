def update_connector(connector_id: str, enabled: bool, fields: dict[str, Any]) -> None:
    """Enable/disable and configure a single connector, merging into
    `~/.jarvis/mcp.json` the same way save_mcp_config() does for that
    integration.

    `fields` maps cfg-key field names (e.g. "elevenlabs_key") to new values.
    Empty/missing values are treated as "no change" — the existing stored
    value (if any) is preserved, so a masked-and-unchanged secret sent back
    from the frontend doesn't blow away the real value.
    """
    connector = _CONNECTORS_BY_ID.get(connector_id)
    if connector is None:
        raise ValueError(f"unknown connector: {connector_id}")

    data = _load_config()
    servers: dict[str, Any] = data.setdefault("mcpServers", {})

    if enabled:
        existing = servers.get(connector_id)
        merged: dict[str, str] = {}
        for f in connector["fields"]:
            name = f["name"]
            new_value = str(fields.get(name, "") or "").strip()
            if new_value:
                merged[name] = new_value
            elif existing is not None:
                merged[name] = _extract_value(existing, name)
            else:
                merged[name] = ""
        servers[connector_id] = _build_server_entry(connector_id, merged)
    else:
        servers.pop(connector_id, None)

    if not servers:
        if MCP_CONFIG_PATH.exists():
            MCP_CONFIG_PATH.unlink()
        return

    data["_comment"] = _COMMENT
    JARVIS_DIR.mkdir(parents=True, exist_ok=True)
    MCP_CONFIG_PATH.write_text(json.dumps(data, indent=2), encoding="utf-8")
